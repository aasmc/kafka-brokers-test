#!/usr/bin/env bash
# Останавливает сервис, запущенный через start-app.sh.
# Первая строка (#!/usr/bin/env bash, «шебанг») говорит системе запускать файл через bash.

# Корень репозитория: каталог скрипта ($0 — путь к нему), на уровень выше, в виде абсолютного пути.
ROOT="$(cd "$(dirname "$0")/.." && pwd)"

# Одна цепочка через &&: каждая следующая команда выполняется, только если предыдущая успешна.
#   [[ -f .../app.pid ]]         — файл с PID сервиса существует (иначе сервис не запущен — ничего не делаем);
#   kill "$(cat .../app.pid)"    — читаем PID из файла и отправляем процессу SIGTERM (Spring завершится корректно),
#                                  2>/dev/null скрывает ошибку, если процесса уже нет;
#   rm -f .../app.pid            — удаляем файл с PID;
#   echo                         — сообщаем об остановке.
[[ -f "$ROOT/logs/app.pid" ]] && kill "$(cat "$ROOT/logs/app.pid")" 2>/dev/null && rm -f "$ROOT/logs/app.pid" && echo "сервис остановлен"
